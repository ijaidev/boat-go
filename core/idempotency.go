package core

import (
	"crypto/rand"
	"fmt"
)

// NewIdempotencyKey returns a random UUIDv4 suitable for the Idempotency-Key header.
//
// The SDK generates one key per logical create or fork and reuses it verbatim across retries.
func NewIdempotencyKey() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", fmt.Errorf("boat: generate idempotency key: %w", err)
	}
	b[6] = (b[6] & 0x0f) | 0x40 // version 4
	b[8] = (b[8] & 0x3f) | 0x80 // variant 10
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16]), nil
}
